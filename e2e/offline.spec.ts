import { expect, test } from '@playwright/test'

test('a saved custom pack remains available after an offline reload', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open Impostor' }).click()
  await page.getByRole('button', { name: 'Create new session' }).click()
  await page.getByLabel('Session name').fill('Offline Session')
  await page.getByRole('button', { name: 'Set up session' }).click()
  await page.getByRole('button', { name: 'Manage custom packs' }).click()

  await page.getByLabel('Pack name').fill('Offline Friends')
  await page.getByLabel('Word 1').fill('Mina')
  await page.getByLabel('Hint 1').fill('Designer')
  await page.getByRole('button', { name: 'Add another word' }).click()
  await page.getByRole('textbox', { name: 'Word 2', exact: true }).fill('Tomas')
  await page.getByLabel('Hint 2').fill('Musician')
  await page.getByRole('button', { name: 'Save pack' }).click()
  await expect(page.getByText('Pack saved on this device.')).toBeVisible()
  await expect(page.getByText('Offline Friends')).toBeVisible()

  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await context.setOffline(true)
  await page.reload()

  await expect(page.getByRole('heading', { name: 'MoldyParty' })).toBeVisible()
  await page.getByRole('button', { name: 'Open Impostor' }).click()
  await page.getByRole('button', { name: 'Create new session' }).click()
  await page.getByLabel('Session name').fill('Offline Reload')
  await page.getByRole('button', { name: 'Set up session' }).click()
  await page.getByRole('button', { name: 'Manage custom packs' }).click()
  await expect(page.getByText('Offline Friends')).toBeVisible()

  await page.goto('/')
  await page.getByRole('button', { name: 'Open Forehead Charades' }).click()
  await page.getByText('Offline Friends', { exact: true }).click()
  await expect(page.getByText('2 cards', { exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: /Tilt controls/ }).uncheck()
  await page.getByRole('checkbox', { name: /Sound/ }).uncheck()
  await page.getByRole('checkbox', { name: /Haptics/ }).uncheck()
  await page.clock.install()
  await page.getByRole('button', { name: 'Start game' }).click()
  await page.getByRole('button', { name: 'Start Get Ready' }).click()
  await page.clock.fastForward(3_000)
  await expect(page.getByRole('button', { name: 'Correct' })).toBeVisible()
  await page.getByRole('button', { name: 'Correct' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Correct' })).toBeVisible()
  await page.clock.fastForward(60_000)
  await expect(page.getByRole('heading', { name: 'Round recap' })).toBeVisible()
  await expect(page.getByText('1 point')).toBeVisible()
})

test('an active Category Bomb game recovers after an offline reload', async ({ page, context }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open Category Bomb' }).click()
  for (const [index, name] of ['Alex', 'Blair', 'Casey'].entries()) {
    await page.getByLabel(`Player ${index + 1} name`).fill(name)
  }
  await page.getByRole('checkbox', { name: /Sound/ }).uncheck()
  await page.getByRole('checkbox', { name: /Haptics/ }).uncheck()
  await page.getByRole('button', { name: 'Arrange players' }).click()
  await page.getByRole('button', { name: 'Arm bomb' }).click()
  await expect(page.getByTestId('category-bomb-arrow')).toBeVisible()

  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload()
  await context.setOffline(true)
  await page.reload()

  await expect(page.getByRole('heading', { name: 'MoldyParty' })).toHaveCount(0)
  await expect(page.getByTestId('category-bomb-arrow')).toBeVisible()
  await expect(page.getByRole('button', { name: /Accept .* answer and pass/ })).toBeVisible()
})
